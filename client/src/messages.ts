export type Key = keyof typeof messages;

/// The text a key names, with `{name}` filled from `vars`.
export function t(key: Key, vars?: Record<string, string | number>): string {
  const text: string = messages[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/// A text that says a count, `n`, read right for one: the key's `_one` form where it has one ("1 matter left", "Told
/// you once"), else the key's own text, filled with `n` and `vars`; `vars.n` writes the count another way where it
/// is shown formatted (tokens, characters). Every count the page says goes through this.
export function tn(key: Key, n: number, vars: Record<string, string | number> = {}): string {
  const one = `${key}_one`;
  return t(n === 1 && one in messages ? (one as Key) : key, { n, ...vars });
}


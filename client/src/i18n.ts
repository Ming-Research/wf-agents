export type Lang = 'en' | 'zh';

export const catalogs: Record<Lang, Record<Key, string>> = { en, zh };

// The catalog for the language the configuration names, such as "Chinese"; English for any other.
export function langOf(configured: string | null | undefined): Lang {
  return configured && /^(chinese|zh|中文|汉语)/i.test(configured.trim()) ? 'zh' : 'en';
}

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const text = catalogs[lang][key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
